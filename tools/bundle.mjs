#!/usr/bin/env node
// Bundles the ES modules under js/ into one classic script (js/app.bundle.js) and wraps the road
// graph into data/mumbai-roads.js. Browsers refuse to load ES modules and fetch() JSON from file://
// URLs, so these two plain scripts let index.html work even when opened straight from disk.
// The ES modules remain the source of truth (they are what the unit tests import).
//
//   npm run bundle        (re-run after editing anything in js/ or data/mumbai-roads.json)
//   node tools/bundle.mjs --check   → exits 1 if the committed bundle is out of date

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';

const root = resolve(dirname(new URL(import.meta.url).pathname), '..');
const entry = join(root, 'js/ui/app.js');
const IMPORT_RE = /^import\s*\{([^}]*)\}\s*from\s*'([^']+)';?\s*$/gm;
const EXPORT_RE = /^export\s+(?:async\s+)?(?:function\*?|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm;

function collect(file, order = [], seen = new Set()) {
  if (seen.has(file)) return order;
  seen.add(file);
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(IMPORT_RE)) collect(resolve(dirname(file), m[2]), order, seen);
  order.push(file);
  return order;
}

export function buildBundle() {
  const files = collect(entry);
  const id = (f) => `__m_${relative(root, f).replace(/[^\w]/g, '_')}`;
  let out = '/* Generated by tools/bundle.mjs — do not edit; edit the ES modules in js/ instead. */\n(function () {\n\'use strict\';\n';
  for (const f of files) {
    let src = readFileSync(f, 'utf8');
    const exports = [...src.matchAll(EXPORT_RE)].map((m) => m[1]);
    src = src.replace(IMPORT_RE, (_, names, from) => {
      const spec = names.split(',').map((n) => n.trim()).filter(Boolean).map((n) => n.replace(/\s+as\s+/, ': ')).join(', ');
      return `const { ${spec} } = ${id(resolve(dirname(f), from))};`;
    });
    src = src.replace(/^export\s+(?=(async\s+)?(function|class|const|let|var)\b)/gm, '');
    if (/^\s*export\s/m.test(src) || /(^|[^{\w.])import\s*\(/m.test(src) || /import\.meta/.test(src)) {
      throw new Error(`Unsupported module syntax in ${relative(root, f)}`);
    }
    out += `\n// ---- ${relative(root, f)} ----\nconst ${id(f)} = (function () {\n${src}\nreturn { ${exports.join(', ')} };\n})();\n`;
  }
  out += '})();\n';
  return out;
}

export function buildData() {
  const p = join(root, 'data/mumbai-roads.json');
  if (!existsSync(p)) return null;
  return `/* Generated by tools/bundle.mjs from data/mumbai-roads.json (OpenStreetMap, ODbL). */\nwindow.MUMBAI_ROADS = ${readFileSync(p, 'utf8').trim()};\n`;
}

const targets = [['js/app.bundle.js', buildBundle()], ['data/mumbai-roads.js', buildData()]];
if (process.argv.includes('--check')) {
  const stale = targets.filter(([p, c]) => c != null && (!existsSync(join(root, p)) || readFileSync(join(root, p), 'utf8') !== c)).map(([p]) => p);
  if (stale.length) { console.error(`Out of date: ${stale.join(', ')} — run npm run bundle`); process.exit(1); }
  console.log('Bundle and data script are up to date.');
} else {
  for (const [p, c] of targets) if (c != null) { writeFileSync(join(root, p), c); console.log(`wrote ${p} (${(c.length / 1024).toFixed(0)} KB)`); }
}
